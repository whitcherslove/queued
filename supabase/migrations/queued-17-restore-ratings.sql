create temp table matched on commit drop as
select distinct on (l.id, s.title) l.id as library_id, l.user_id, s.title, s.year
  from public.library l
  join public.titles t on t.id = l.title_id
  join src_overall s on lower(regexp_replace(t.title, '[^a-zA-Z0-9]+', '', 'g')) = lower(regexp_replace(s.title, '[^a-zA-Z0-9]+', '', 'g'))
         and (s.year is null or t.year is null or abs(t.year - s.year) <= 1)
 where l.section = 'tv'
 order by l.id, s.title;

-- 1) overall rating
update public.library l
   set tier = s.tier, score = s.score
  from matched m join src_overall s on s.title = m.title and s.year is not distinct from m.year
 where l.id = m.library_id;

-- 2) season ratings: remove the ones the earlier SQL invented (old date, not in your table), then write the table's ones
update public.season_ratings r
   set tier = null, score = null
  from matched m
 where r.library_id = m.library_id and r.rated_at < date '2026-10-28'
   and not exists (select 1 from src_seasons s where s.title = m.title and s.year is not distinct from m.year and s.season = r.season);

insert into public.season_ratings (user_id, library_id, season, tier, score, rated_at)
select m.user_id, m.library_id, s.season, s.tier, null, coalesce(s.rated, current_date)
  from matched m join src_seasons s on s.title = m.title and s.year is not distinct from m.year
on conflict (library_id, season) do update
   set tier = excluded.tier, score = case when public.season_ratings.rated_at >= date '2026-10-28' then public.season_ratings.score else null end,
       rated_at = excluded.rated_at
 where public.season_ratings.rated_at < date '2026-10-28';

-- 3) journal entries: their own row rating back
update public.logs g
   set tier = case when e.dropped then null else e.tier end, score = e.score, dropped = e.dropped
  from matched m join src_entries e on e.title = m.title and e.year is not distinct from m.year
 where g.library_id = m.library_id and g.watched_at::date = e.finished;

